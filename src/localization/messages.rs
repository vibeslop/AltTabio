#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    fn placeholders(text: &str) -> BTreeSet<&str> {
        text.split('{')
            .skip(1)
            .filter_map(|part| part.split_once('}').map(|(key, _)| key))
            .collect()
    }

    #[test]
    fn every_translation_is_complete_unique_and_preserves_placeholders() {
        let mut sources = BTreeSet::new();
        for &(en, ru, zh) in MESSAGES {
            assert!(sources.insert(en), "duplicate source: {en}");
            for translated in [ru, zh] {
                assert!(!translated.trim().is_empty(), "missing translation: {en}");
                assert_eq!(
                    placeholders(en),
                    placeholders(translated),
                    "placeholders for {en}"
                );
            }
        }
    }
}
