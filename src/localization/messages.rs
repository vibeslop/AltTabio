//! English source messages and their Russian and Simplified Chinese translations.
use super::Language;

macro_rules! messages {
    ($(($en:expr, $ru:expr, $zh:expr)),+ $(,)?) => {
        pub(super) fn translate(language: Language, source: &str) -> &str {
            match language {
                Language::Russian => match source { $($en => $ru,)+ _ => source },
                Language::SimplifiedChinese => match source { $($en => $zh,)+ _ => source },
                Language::System | Language::English => source,
            }
        }
        #[cfg(test)]
        const MESSAGES: &[(&str, &str, &str)] = &[$(($en, $ru, $zh),)+];
    };
}

